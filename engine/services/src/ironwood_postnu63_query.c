static void global_query(size_t n, size_t ordinal, struct ironwood_opening_query *q)
{
    q->count = 1;
    if (ordinal == 0) {
        q->source = IRONWOOD_QUERY_WIRE;
        q->point = 22*n;
        q->evaluation[0] = 26*n + 29;
    } else if (ordinal == 1) {
        q->source = IRONWOOD_QUERY_H;
    } else {
        q->source = IRONWOOD_QUERY_VK;
        q->point = ordinal - 2;
        q->vk = vk_points[q->point];
        q->evaluation[0] = 26*n + (q->point < 15 ? 44 : 43) - q->point;
    }
}

static void lookup_query(size_t n, size_t a, size_t row, struct ironwood_opening_query *q)
{
    size_t lookup = 2 - row/3;
    size_t input = 10*n + 6*a + 2*lookup;
    size_t first = 34*n + 45 + 15*a + 5*lookup;
    if (row%3 == 0) {
        q->point = input + 1; q->count = 1; q->evaluation[0] = first + 4;
    } else if (row%3 == 1) {
        q->point = input; q->set = 4; q->count = 2;
        q->evaluation[0] = first + 2; q->evaluation[1] = first + 3;
    } else {
        q->point = 19*n + 3*a + lookup; q->set = 1; q->count = 2;
        q->evaluation[0] = first; q->evaluation[1] = first + 1;
    }
}

static void action_query(size_t n, size_t a, size_t row, struct ironwood_opening_query *q)
{
    q->source = IRONWOOD_QUERY_WIRE;
    if (row < 9) {
        lookup_query(n, a, row, q);
    } else if (row < 12) {
        size_t j = 11 - row;
        q->point = 16*n + 3*a + j;
        q->count = j == 2 ? 2 : 3;
        q->set = j == 2 ? 1 : 3;
        for (unsigned k = 0; k < q->count; ++k) q->evaluation[k] = 26*n + 45 + 8*a + 3*j + k;
    } else if (row < 22) {
        size_t j = 21 - row;
        q->point = 10*a + j;
        q->count = advice[j].count; q->set = advice[j].set;
        for (unsigned k = 0; k < q->count; ++k) q->evaluation[k] = n + 25*a + advice[j].slot[k];
    } else {
        q->source = IRONWOOD_QUERY_INSTANCE; q->point = a;
        q->count = 1; q->evaluation[0] = a;
    }
}

struct zcl_result ironwood_postnu63_query_at(uint64_t actions, size_t ordinal,
                                             struct ironwood_opening_query *out)
{
    size_t bytes = 0;
    struct zcl_result r = ironwood_postnu63_proof_size(actions, &bytes);
    if (!r.ok) return r;
    size_t n = (size_t)actions;
    if (!out || ordinal >= IRONWOOD_SHARED_OPENING_QUERIES + IRONWOOD_ACTION_OPENING_QUERIES * n) return ZCL_ERR(-1, "Invalid PostNu6_3 opening query ordinal");
    struct ironwood_opening_query q = {0};
    if (ordinal < IRONWOOD_SHARED_OPENING_QUERIES) global_query(n, ordinal, &q);
    else {
        size_t action_row = ordinal - IRONWOOD_SHARED_OPENING_QUERIES;
        action_query(n, n - 1 - action_row / IRONWOOD_ACTION_OPENING_QUERIES,
                     action_row % IRONWOOD_ACTION_OPENING_QUERIES, &q);
    }
    *out = q;
    return ZCL_OK;
}
