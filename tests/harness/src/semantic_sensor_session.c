static bool sss_write(const char *root, const char *rel, const char *body)
{
    char path[PATH_MAX];
    FILE *fp;
    bool ok;
    for (const char *s = strchr(rel, '/'); s != NULL; s = strchr(s + 1, '/')) {
        (void)snprintf(path, sizeof(path), "%s/%.*s", root, (int)(s - rel), rel);
        if (mkdir(path, 0700) != 0 && errno != EEXIST)
            return false;
    }
    (void)snprintf(path, sizeof(path), "%s/%s", root, rel);
    fp = fopen(path, "wb");
    if (fp == NULL)
        return false;
    ok = fputs(body, fp) >= 0;
    return fclose(fp) == 0 && ok;
}

static bool sss_read(const char *path, char **out, size_t *len)
{
    FILE *fp = fopen(path, "rb");
    long size;
    bool ok = false;
    *out = NULL;
    if (fp == NULL)
        return false;
    if (fseek(fp, 0, SEEK_END) == 0 && (size = ftell(fp)) >= 0 &&
        fseek(fp, 0, SEEK_SET) == 0) {
        *out = malloc((size_t)size + 1);
        ok = *out != NULL && fread(*out, 1, (size_t)size, fp) == (size_t)size;
        *len = (size_t)size;
    }
    (void)fclose(fp);
    if (ok)
        (*out)[*len] = '\0';
    return ok;
}

/* Replace the first `from` in root/rel with `to`. */
static bool sss_edit(const char *root, const char *rel, const char *from,
                     const char *to)
{
    char path[PATH_MAX], next[8192];
    char *body = NULL, *hit;
    size_t n = 0;
    bool ok = false;
    (void)snprintf(path, sizeof(path), "%s/%s", root, rel);
    if (!sss_read(path, &body, &n))
        return false;
    hit = strstr(body, from);
    if (hit != NULL && n + strlen(to) < sizeof(next)) {
        (void)snprintf(next, sizeof(next), "%.*s%s%s", (int)(hit - body), body,
                       to, hit + strlen(from));
        ok = sss_write(root, rel, next);
    }
    free(body);
    return ok;
}

static bool sss_tree(const char *root)
{
    char dir[PATH_MAX];
    (void)snprintf(dir, sizeof(dir), "%s/inc", root);
    if (mkdir(dir, 0700) != 0 && errno != EEXIST)
        return false;
    (void)snprintf(dir, sizeof(dir), "%s/inc/a", root);
    if (mkdir(dir, 0700) != 0 && errno != EEXIST)
        return false;
    return sss_write(root, "inc/b/fx.h", k_sss_header) &&
           sss_write(root, "src/main.c", k_sss_main);
}

