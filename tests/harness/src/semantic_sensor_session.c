/* ── the sensor: cold emits and one session process ─────────────────────── */

struct sss_argv {
    const char *items[9]; /* base (5), system dir, extra flag, two case flags */
    size_t n;
};

static void sss_argv(struct sss_argv *a, bool extra)
{
    /* Keep the builtin stdint.h and controlled system-header fixture, with
     * no hosted SDK's unrelated unbound probes in reparse acceptance. */
    static const char *const base[] = {"-std=c23", "-ffreestanding",
                                       "-Iinc/a", "-Iinc/b", "-DFX_MODE=1"};
    a->n = 0;
    for (size_t k = 0; k < sizeof(base) / sizeof(base[0]); k++)
        a->items[a->n++] = base[k];
    a->items[a->n++] = g_sss_system_flag;
    if (extra)
        a->items[a->n++] = "-DFX_EXTRA=1";
}

static bool sss_cold(const char *sensor, const char *root, const char *out,
                     const struct sss_argv *a)
{
    const char *argv[26];
    char buf[4096];
    bool timed_out = false;
    size_t k = 0;
    int rc;
    argv[k++] = "env";
    argv[k++] = g_sss_child_home;
    const char *head[] = {sensor, "emit", "--root", root, "--source",
                          "src/main.c", "--out", out, "--facts", "--"};
    for (size_t i = 0; i < sizeof(head) / sizeof(head[0]); i++)
        argv[k++] = head[i];
    for (size_t i = 0; i < a->n; i++)
        argv[k++] = a->items[i];
    argv[k] = NULL;
    rc = zcl_spawn_capture_merged_observed(argv, buf, sizeof(buf), 60000,
                                           &timed_out);
    if (rc != 0)
        printf("FAIL cold emit exited %d: %s\n", rc, buf);
    return rc == 0;
}

/* Cold `emit` with an explicit --cc / --toolchain-id (either may be NULL).
 * message carries stdout+stderr; the caller checks rc itself, so a refused
 * emit (a bad --cc or --toolchain-id) is not itself a FAIL here. */
static int sss_cold_cc(const char *sensor, const char *root, const char *out,
                       const char *cc, const char *tc,
                       const struct sss_argv *a, char *message, size_t cap)
{
    const char *argv[30];
    bool timed_out = false;
    size_t k = 0;
    argv[k++] = "env";
    argv[k++] = g_sss_child_home;
    const char *head[] = {sensor, "emit", "--root", root, "--source",
                          "src/main.c", "--out", out, "--facts"};
    for (size_t i = 0; i < sizeof(head) / sizeof(head[0]); i++)
        argv[k++] = head[i];
    if (cc != NULL) {
        argv[k++] = "--cc";
        argv[k++] = cc;
    }
    if (tc != NULL) {
        argv[k++] = "--toolchain-id";
        argv[k++] = tc;
    }
    argv[k++] = "--";
    for (size_t i = 0; i < a->n; i++)
        argv[k++] = a->items[i];
    argv[k] = NULL;
    return zcl_spawn_capture_merged_observed(argv, message, cap, 60000,
                                             &timed_out);
}

struct sss_proc {
    pid_t pid;
    int to, from;
    char buf[SSS_REPLY_MAX * 2];
    size_t have;
};

/* Only sensor children use the fixture project as HOME. Its sibling system
 * fixture stays outside both root and home, regardless of the host checkout
 * location. Parent environment and production home guard remain unchanged. */
static char **sss_env(bool inject)
{
    size_t n = 0, w = 0;
    char **env;
    while (environ[n] != NULL)
        n++;
    env = calloc(n + 3, sizeof(char *));
    if (env == NULL)
        return NULL;
    for (size_t k = 0; k < n; k++) {
        if (strncmp(environ[k], SSS_INJECT "=", sizeof(SSS_INJECT)) != 0 &&
            strncmp(environ[k], "HOME=", 5) != 0)
            env[w++] = environ[k];
    }
    env[w++] = g_sss_child_home;
    if (inject)
        env[w++] = SSS_INJECT "=1";
    return env;
}

/* Start `sensor session opt...` (opt: up to 3, NULL-terminated early). */
static bool sss_start_opts(struct sss_proc *p, const char *sensor,
                           const char *const opt[3], bool inject,
                           const char *err_log)
{
    char *argv[6] = {(char *)sensor, "session"};
    for (size_t k = 0; k < 3 && opt[k] != NULL; k++)
        argv[2 + k] = (char *)opt[k];
    char **env = sss_env(inject);
    int in[2], out[2];
    if (env == NULL || pipe(in) != 0 || pipe(out) != 0) {
        free(env);
        return false;
    }
    p->pid = fork();
    if (p->pid == 0) {
        int fd = open(err_log, O_WRONLY | O_CREAT | O_TRUNC, 0600);
        (void)dup2(in[0], 0);
        (void)dup2(out[1], 1);
        if (fd >= 0)
            (void)dup2(fd, 2);
        (void)close(in[1]);
        (void)close(out[0]);
        execve(sensor, argv, env);
        _exit(127);
    }
    free(env);
    (void)close(in[0]);
    (void)close(out[1]);
    p->to = in[1];
    p->from = out[0];
    p->have = 0;
    return p->pid > 0;
}

static bool sss_start(struct sss_proc *p, const char *sensor, bool verify,
                      bool inject, const char *err_log)
{
    const char *opt[3] = {verify ? "--verify-cold" : NULL, NULL, NULL};
    return sss_start_opts(p, sensor, opt, inject, err_log);
}

static bool sss_write_all(int fd, const char *s, size_t n)
{
    struct sigaction ign = {.sa_handler = SIG_IGN}, old;
    bool ok = true;
    (void)sigaction(SIGPIPE, &ign, &old);
    while (ok && n > 0) {
        ssize_t w = write(fd, s, n);
        ok = w > 0;
        if (ok) {
            s += w;
            n -= (size_t)w;
        }
    }
    (void)sigaction(SIGPIPE, &old, NULL);
    return ok;
}

/* Admit the measured record before exposing it through a C string. */
static bool sss_copy_record(const char *bytes, size_t n, char *out, size_t cap)
{
    if (n >= cap || memchr(bytes, '\0', n) != NULL ||
        !zutf8_validate_n(bytes, n)) return false;
    memcpy(out, bytes, n);
    out[n] = '\0';
    return true;
}

/* One stdout record, without its newline, including a final EOF record. */
static bool sss_line(struct sss_proc *p, char *out, size_t cap)
{
    for (;;) {
        char *nl = memchr(p->buf, '\n', p->have);
        struct pollfd pf = {.fd = p->from, .events = POLLIN};
        ssize_t got;
        if (nl != NULL) {
            size_t n = (size_t)(nl - p->buf);
            bool valid = sss_copy_record(p->buf, n, out, cap);
            memmove(p->buf, nl + 1, p->have - n - 1);
            p->have -= n + 1;
            return valid;
        }
        if (p->have == sizeof(p->buf) || poll(&pf, 1, 120000) <= 0)
            return false;
        got = read(p->from, p->buf + p->have, sizeof(p->buf) - p->have);
        if (got == 0 && p->have != 0) {
            bool valid = sss_copy_record(p->buf, p->have, out, cap);
            p->have = 0;
            return valid;
        }
        if (got <= 0)
            return false;
        p->have += (size_t)got;
    }
}

/* The request text of one emit, without its newline; its length, or 0. */
static size_t sss_request_text(const char *root, const char *source,
                               const char *out, const struct sss_argv *a,
                               char *line, size_t cap)
{
    int w = snprintf(line, cap,
                     "emit\t--root\t%s\t--source\t%s\t--out\t%s\t--facts\t--",
                     root, source, out);
    for (size_t k = 0; k < a->n && w > 0 && (size_t)w < cap; k++)
        w += snprintf(line + w, cap - (size_t)w, "\t%s", a->items[k]);
    return w <= 0 || (size_t)w + 2 > cap ? 0 : (size_t)w;
}

/* Like sss_request_text, with --cc / --toolchain-id inserted before `--`
 * (either may be NULL). */
static size_t sss_request_text_cc(const char *root, const char *source,
                                  const char *out, const char *cc,
                                  const char *tc, const struct sss_argv *a,
                                  char *line, size_t cap)
{
    int w = snprintf(line, cap, "emit\t--root\t%s\t--source\t%s\t--out\t%s"
                                "\t--facts", root, source, out);
    if (w > 0 && cc != NULL)
        w += snprintf(line + w, cap - (size_t)w, "\t--cc\t%s", cc);
    if (w > 0 && tc != NULL)
        w += snprintf(line + w, cap - (size_t)w, "\t--toolchain-id\t%s", tc);
    if (w > 0)
        w += snprintf(line + w, cap - (size_t)w, "\t--");
    for (size_t k = 0; k < a->n && w > 0 && (size_t)w < cap; k++)
        w += snprintf(line + w, cap - (size_t)w, "\t%s", a->items[k]);
    return w <= 0 || (size_t)w + 2 > cap ? 0 : (size_t)w;
}

static bool sss_request(struct sss_proc *p, const char *root, const char *out,
                        const struct sss_argv *a, char *reply, size_t cap)
{
    char line[8192];
    size_t w = sss_request_text(root, "src/main.c", out, a, line, sizeof(line));
    if (w == 0)
        return false;
    line[w++] = '\n';
    return sss_write_all(p->to, line, w) && sss_line(p, reply, cap);
}

/* End the session: its summary line, then its exit status. */
static int sss_finish(struct sss_proc *p, char *summary, size_t cap)
{
    int status = -1;
    (void)close(p->to);
    if (!sss_line(p, summary, cap))
        summary[0] = '\0';
    (void)close(p->from);
    if (waitpid(p->pid, &status, 0) != p->pid)
        return -1;
    return WIFEXITED(status) ? WEXITSTATUS(status) : -1;
}

static bool sss_unique_keys(const struct json_value *v)
{
    for (size_t i = 0; i < v->num_children; i++) {
        if (!sss_unique_keys(&v->children[i])) return false;
        if (v->type != JSON_OBJ) continue;
        for (size_t j = 0; j < i; j++)
            if (strcmp(v->keys[i], v->keys[j]) == 0) return false;
    }
    return true;
}

/* Parse the whole reply before treating any member as evidence. */
static bool sss_reply(const char *reply, struct json_value *v)
{
    size_t n = strlen(reply);
    json_init(v);
    return zutf8_validate_n(reply, n) && json_read(v, reply, n) &&
           v->type == JSON_OBJ && sss_unique_keys(v);
}

/* A decoded string field of a complete, unambiguous JSON reply. */
static bool sss_field(const char *reply, const char *key, char *out,
                      size_t cap)
{
    struct json_value v;
    bool ok = sss_reply(reply, &v);
    const struct json_value *field = json_get(&v, key);
    ok = ok && field != NULL && field->type == JSON_STR;
    const char *s = json_get_str(field);
    size_t n = strlen(s);
    ok = ok && n < cap;
    if (ok) memcpy(out, s, n + 1);
    json_free(&v);
    return ok;
}

static bool sss_is(const char *reply, const char *key, const char *want)
{
    char got[512];
    if (sss_field(reply, key, got, sizeof(got)) && strcmp(got, want) == 0)
        return true;
    printf("FAIL reply %s is not \"%s\": %s\n", key, want, reply);
    return false;
}

static bool sss_starts(const char *reply, const char *key, const char *prefix)
{
    char got[512];
    if (sss_field(reply, key, got, sizeof(got)) &&
        strncmp(got, prefix, strlen(prefix)) == 0)
        return true;
    printf("FAIL reply %s does not start \"%s\": %s\n", key, prefix, reply);
    return false;
}

static bool sss_same(const char *x, const char *y)
{
    char *a = NULL, *b = NULL;
    size_t an = 0, bn = 0;
    bool same = sss_read(x, &a, &an) && sss_read(y, &b, &bn) && an == bn &&
                memcmp(a, b, an) == 0;
    free(a);
    free(b);
    if (!same)
        printf("FAIL %s and %s differ\n", x, y);
    return same;
}

