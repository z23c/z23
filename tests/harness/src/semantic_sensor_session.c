/* ── the stdin protocol ───────────────────────────────────────────────────── */

/* Send n bytes as one request (the caller supplies the newline). */
static bool sss_send(struct sss_proc *p, const char *line, size_t n,
                     char *reply, size_t cap)
{
    return sss_write_all(p->to, line, n) && sss_line(p, reply, cap);
}

/* No byte of a reply is outside ASCII: JSON escapes carry the rest. */
static bool sss_ascii(const char *reply)
{
    for (const unsigned char *s = (const unsigned char *)reply; *s; s++) {
        if (*s >= 0x80) {
            printf("FAIL reply carries a raw byte 0x%02x: %s\n", *s, reply);
            return false;
        }
    }
    return true;
}

static bool sss_refused(const char *reply, const char *why)
{
    struct json_value v;
    bool valid = sss_reply(reply, &v);
    const struct json_value *ok = json_get(&v, "ok");
    bool refused = valid && ok != NULL && ok->type == JSON_BOOL && !ok->val.b;
    json_free(&v);
    if (!refused) return false;
    return why == NULL || sss_starts(reply, "why", why);
}

