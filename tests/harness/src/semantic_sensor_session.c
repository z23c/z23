/* An asm label in a header (inside the preamble), and in the main file a
 * cleanup(f) local and an alias("x") definition: the attribute call refs and
 * alias address refs the facts extractor derives by tokenizing attribute
 * extents. A reparse must derive them exactly as a cold parse does. */
static bool sss_attr_setup(const char *root)
{
    return sss_write(root, "inc/b/fx_attr.h",
                     "int fx_label(int v) __asm__(\"fx_label_impl\");\n") &&
           sss_edit(root, "src/main.c", "#include <stdint.h>\n",
                    "#include <stdint.h>\n#include \"fx_attr.h\"\n") &&
           sss_edit(root, "src/main.c", "    return fx_sum(&p) * 2;\n}\n",
                    "    return fx_sum(&p) * 2;\n}\n"
                    "static void fx_drop(int *p) { (void)p; }\n"
                    "int fx_orig(int v)\n{\n"
                    "    int t __attribute__((cleanup(fx_drop))) = "
                    "v + fx_label(v);\n"
                    "    return t;\n}\n"
                    "int fx_alias(int v) __attribute__((alias(\"fx_orig\")));\n");
}

