/* ── inputs a key could miss: decided directly over the fixture ──────── */

#define DE_HOLE_A "tools/dev/early_hole_a.c"
#define DE_HOLE_B "tools/dev/early_hole_b.c"
#define DE_HOLE_FLAGS "-DZCL_TESTING -O0 -Itests/harness/include"

/* One row, the vouched group, over restart sources A and B, both linked
 * into the candidate its test binary runs. */
static void de_hole_decide(struct de_state *s, const char *cflags)
{
    static const char *const sources[] = { DE_HOLE_A, DE_HOLE_B };
    const struct zcl_devloop_early_toolchain tc = {
        .compiler_id = "fixture-cc", .base_generation = "fixture-base",
        .cflags = cflags, .ldflags = "-pthread", .libs = "-lm",
        .sources = sources, .source_count = 2,
    };
    memset(&s->hole, 0, sizeof(s->hole));
    s->hole.n = 1;
    (void)snprintf(s->hole.rows[0].group, sizeof(s->hole.rows[0].group),
                   "%s", DE_VOUCHED);
    zcl_devloop_early_skip_decide(s->fx.root, &tc, &s->hole);
}

/* The row's reason is `reason` and its detail holds `detail`. */
static bool de_hole_is(const struct de_state *s, const char *reason,
                       const char *detail)
{
    const struct zcl_devloop_early_skip_row *row = &s->hole.rows[0];
    bool ok = row->reason && strcmp(row->reason, reason) == 0 &&
              strstr(row->detail, detail) != NULL &&
              row->skip == (strcmp(reason, "closure-unchanged") == 0) &&
              row->vouched == (strcmp(reason, "unvouched") != 0);
    if (!ok)
        printf("[hole: %s %s] ", row->reason ? row->reason : "(none)",
               row->detail);
    return ok;
}

