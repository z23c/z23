#define DE_SKIP_ENV "ZCL_DEVLOOP_EARLY_SKIP"
#define DE_VOUCHED "test_devloop_early"
#define DE_UNVOUCHED "test_devagent_ticketkey"
#define DE_DEP_H "tests/harness/src/early_skip_dep.h"

/* A facts-narrowed plan naming `n` path groups, never admissible. */
static bool de_skip_plan(const struct zcl_devloop_plan *proof,
                         const char *const *groups, size_t n,
                         struct zcl_devloop_early_plan *early)
{
    memset(early, 0, sizeof(*early));
    early->plan = *proof;
    for (size_t i = 0; i < n; i++)
        (void)snprintf(early->plan.path_groups[i],
                       sizeof(early->plan.path_groups[i]), "%s", groups[i]);
    early->plan.path_groups_len = n;
    early->plan.closure_groups_len = 0;
    early->plan.dims[ZCL_DEVLOOP_DIM_SEMANTIC].status =
        ZCL_DEVLOOP_DIM_INCOMPLETE;
    early->ready = true;
    early->skip_reason = "";
    early->origin_us = platform_time_monotonic_us();
    return !zcl_devloop_plan_proof_admissible(&early->plan, NULL);
}

/* The vouched group's test file includes a header beside it; the other
 * group's test file reads the environment, which no key names. */
static bool de_skip_files(const struct de_fixture *fx, const char *dep)
{
    return de_write(fx->root, "tests/harness/src/" DE_VOUCHED ".c",
                    "#include \"early_skip_dep.h\"\n"
                    "int early_skip_fixture_group = EARLY_SKIP_DEP;\n"
                    "const char *early_skip_inert_literal(void)\n"
                    "{ return \"__DATE__\"; }\n") &&
           de_write(fx->root, DE_DEP_H, dep) &&
           de_write(fx->root, "tests/harness/src/" DE_UNVOUCHED ".c",
                    "#include <stdlib.h>\n"
                    "const char *early_skip_env(void)\n"
                    "{ return getenv(\"EARLY_SKIP_FIXTURE\"); }\n");
}

/* A fresh full proof with no early stage, over the tree as it is now: the
 * receipt every later run must reproduce byte for byte. */
static bool de_skip_base(struct de_state *s)
{
    const char *changed[] = { DE_CHANGED };
    bool ok = zcl_devloop_restart_prove(s->fx.root, changed, 1,
                                        &s->proof_plan, &s->base, &s->process,
                                        s->why, sizeof(s->why)) &&
              s->base.proof_complete;
    (void)unlink(s->fx.log);
    return ok;
}

static const struct zcl_devloop_early_skip_row *de_row(
    const struct zcl_devloop_early_receipt *r, const char *group)
{
    for (size_t i = 0; i < r->skip.n; i++)
        if (strcmp(r->skip.rows[i].group, group) == 0)
            return &r->skip.rows[i];
    return NULL;
}

static bool de_row_is(const struct zcl_devloop_early_receipt *r,
                      const char *group, const char *reason, bool skip)
{
    const struct zcl_devloop_early_skip_row *row = de_row(r, group);
    bool ok = row && row->reason && strcmp(row->reason, reason) == 0 &&
              row->skip == skip;
    if (!ok)
        printf("[row %s: %s %s] ", group,
               row && row->reason ? row->reason : "(none)",
               row ? row->detail : "");
    return ok;
}

static int64_t de_json_int(const struct json_value *o, const char *key)
{
    const struct json_value *v = o ? json_get(o, key) : NULL;
    return v ? json_get_int(v) : -1;
}

/* The early_feedback counters say `run` ran and `skipped` were skipped as
 * closure-unchanged, and the skipped row names its key. */
static bool de_skip_json(const struct zcl_devloop_early_receipt *r,
                         int64_t run, int64_t skipped)
{
    struct json_value doc;
    json_init(&doc);
    json_set_object(&doc);
    zcl_devloop_early_json(r, &doc);
    const struct json_value *e = json_get(&doc, "early_feedback");
    const struct json_value *result = e ? json_get(e, "result") : NULL;
    const struct json_value *timing = e ? json_get(e, "timing") : NULL;
    const struct json_value *cs = e ? json_get(e, "closure_skip") : NULL;
    bool ok = de_json_int(result, "groups_selected") == r->group_count &&
              de_json_int(result, "groups_run") == run &&
              de_json_int(result, "groups_skipped_closure_unchanged") ==
                  skipped &&
              de_json_int(cs, "groups_skipped_closure_unchanged") ==
                  skipped &&
              (skipped == 0 ||
               de_json_int(timing, "estimated_wall_saved_us") > 0) &&
              json_get(cs, "groups") && json_get(cs, "verify");
    json_free(&doc);
    return ok;
}

