static bool de_write(const char *root, const char *rel, const char *body)
{
    char full[PATH_MAX];
    if (snprintf(full, sizeof(full), "%s/%s", root, rel) >= (int)sizeof(full))
        return false;
    for (char *p = full + 1; *p; p++) {
        if (*p != '/')
            continue;
        *p = '\0';
        (void)platform_directory_create(full, 0755);
        *p = '/';
    }
    FILE *f = fopen(full, "wb");
    if (!f)
        return false;
    size_t n = strlen(body);
    bool ok = fwrite(body, 1, n, f) == n;
    return fclose(f) == 0 && ok;
}

static char *de_read(const char *path)
{
    FILE *f = fopen(path, "rb");
    if (!f)
        return NULL;
    char *buf = zcl_calloc(1, 65536, "de.read");
    size_t n = buf ? fread(buf, 1, 65535, f) : 0;
    (void)n;
    fclose(f);
    return buf;
}
