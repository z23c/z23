/* Read one line (no newline) from fd. False on EOF/error/overflow. */
static bool gw_read_line(int fd, char *out, size_t cap)
{
    size_t n = 0;
    while (n + 1 < cap) {
        char c;
        ssize_t r = read(fd, &c, 1);
        if (r <= 0)
            return false;
        if (c == '\n')
            break;
        if (c != '\r')
            out[n++] = c;
    }
    out[n] = '\0';
    return true;
}

/* Spawn the gateway; parse its `ready port=N` line. True when serving.
 * as_kb > 0 caps the child's address space (RLIMIT_AS, the limit ulimit -v
 * sets) so a case can run the same request under exact memory pressure. */
/* stderr of the gateway and of every node it forks, for the leak check. */
static char g_gw_log[1100];

static bool gw_spawn_as(const char *bin, const char *node, const char *state,
                        unsigned long as_kb)
{
    int fds[2];
    char line[256];
    if (snprintf(g_gw_log, sizeof(g_gw_log), "%s/gateway-stderr.log", state) <= 0)
        return false;
    if (pipe(fds) != 0)
        return false;
    g_gw_pid = fork();
    if (g_gw_pid < 0) {
        close(fds[0]);
        close(fds[1]);
        return false;
    }
    if (g_gw_pid == 0) {
        char *const argv[] = {(char *)bin, NULL};
        if (as_kb > 0) {
            struct rlimit rl;
            rl.rlim_cur = (rlim_t)as_kb * 1024u;
            rl.rlim_max = (rlim_t)as_kb * 1024u;
            if (setrlimit(RLIMIT_AS, &rl) != 0)
                _exit(126);
        }
        {
            int lf = open(g_gw_log, O_WRONLY | O_CREAT | O_TRUNC, 0600);
            if (lf >= 0) {
                dup2(lf, STDERR_FILENO);
                close(lf);
            }
        }
        dup2(fds[1], STDOUT_FILENO);
        close(fds[0]);
        close(fds[1]);
        setenv("FLEET_GW_PORT", "0", 1);
        setenv("FLEET_GW_NODE", node, 1);
        setenv("FLEET_GW_OWNER_KEY", "gw-test-owner-key", 1);
        /* Registration is allowlisted now: without an operator entry only
         * loopback callbacks can register at all. This rig's clients live
         * on client.test, so that is what the operator admits. */
        setenv("FLEET_GW_REDIRECT_ALLOW", "https://client.test", 1);
        /* Short socket deadline and a small child cap so the half-open
         * connection case proves itself in a second rather than ten. */
        setenv("FLEET_GW_IO_TIMEOUT_MS", "1000", 1);
        setenv("FLEET_GW_MAX_CHILDREN", "8", 1);
        setenv("XDG_STATE_HOME", state, 1);
        execv(bin, argv);
        _exit(127);
    }
    close(fds[1]);
    if (!gw_read_line(fds[0], line, sizeof(line))) {
        close(fds[0]);
        return false;
    }
    close(fds[0]);
    if (sscanf(line, "ready port=%d", &g_gw_port) != 1 || g_gw_port <= 0)
        return false;
    return true;
}

static bool gw_spawn(const char *bin, const char *node, const char *state)
{
    return gw_spawn_as(bin, node, state, 0);
}

static void gw_stop(void)
{
    int st = 0;
    if (g_gw_pid < 0)
        return;
    kill(g_gw_pid, SIGTERM);
    waitpid(g_gw_pid, &st, 0);
    g_gw_pid = -1;
    g_gw_port = -1;
}

/* Head (status line + headers) of the most recent exchange, for header
 * assertions such as the OAuth challenge. */
static char g_gw_last_head[2048];

/* One HTTP exchange over loopback. Returns the body (after the blank
 * line) malloc'd, with the status code out. NULL on transport failure. */
static char *gw_exchange(const char *request, int *status)
{
    int fd;
    struct sockaddr_in v4;
    char *buf, *body;
    size_t cap = GW_TEST_CAP, n = 0;
    ssize_t r;
    *status = 0;
    g_gw_last_head[0] = '\0';
    fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0)
        return NULL;
    memset(&v4, 0, sizeof(v4));
    v4.sin_family = AF_INET;
    v4.sin_port = htons((uint16_t)g_gw_port);
    v4.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    if (connect(fd, (struct sockaddr *)&v4, sizeof(v4)) != 0) {
        close(fd);
        return NULL;
    }
    {
        size_t left = strlen(request), off = 0;
        while (left > 0) {
            r = write(fd, request + off, left);
            if (r <= 0) {
                close(fd);
                return NULL;
            }
            off += (size_t)r;
            left -= (size_t)r;
        }
    }
    buf = malloc(cap);
    if (!buf) {
        close(fd);
        return NULL;
    }
    for (;;) {
        if (n + 4096 >= cap) {
            close(fd);
            free(buf);
            return NULL;
        }
        r = read(fd, buf + n, cap - n - 1);
        if (r == 0)
            break;
        if (r < 0) {
            close(fd);
            free(buf);
            return NULL;
        }
        n += (size_t)r;
    }
    close(fd);
    buf[n] = '\0';
    if (sscanf(buf, "HTTP/1.1 %d", status) != 1) {
        free(buf);
        return NULL;
    }
    body = strstr(buf, "\r\n\r\n");
    if (!body) {
        free(buf);
        return NULL;
    }
    snprintf(g_gw_last_head, sizeof(g_gw_last_head), "%.*s",
             (int)(body - buf), buf);
    body += 4;
    {
        size_t blen = n - (size_t)(body - buf);
        char *out = malloc(blen + 1);
        if (!out) {
            free(buf);
            return NULL;
        }
        memcpy(out, body, blen);
        out[blen] = '\0';
        free(buf);
        return out;
    }
}

static char *gw_post(const char *path, const char *json, int *status)
{
    char req[GW_TEST_CAP];
    int n = snprintf(req, sizeof(req),
                     "POST %s HTTP/1.1\r\nHost: x\r\nContent-Type: "
                     "application/json\r\nContent-Length: %zu\r\n"
                     "Connection: close\r\n\r\n%s",
                     path, strlen(json), json);
    if (n <= 0 || (size_t)n >= sizeof(req))
        return NULL;
    return gw_exchange(req, status);
}

