/* cursor_token out of a tools/call brief body (the gateway escapes quotes
 * in content, so the value ends at the next quote byte). False when the
 * reply carries no usable watermark. */
static bool gw_body_token(const char *body, char *out, size_t cap)
{
    const char *p;
    size_t n = 0;
    if (!body || !out || cap == 0)
        return false;
    p = strstr(body, "cursor_token");
    if (!p)
        return false;
    p = strchr(p, ':');
    if (!p)
        return false;
    p++;
    if (*p == '\\')
        p++;
    if (*p != '"')
        return false;
    p++;
    /* The reply body is escaped JSON content, so the value's closing
     * quote arrives as \" — stop before the backslash instead of
     * copying it into the token (a trailing backslash would escape
     * the quote of the next request and break parsing). */
    while (*p && *p != '"' && *p != '\\' && n + 1 < cap)
        out[n++] = *p++;
    out[n] = '\0';
    if (n == 0)
        return false;
    return *p == '"' || (*p == '\\' && *(p + 1) == '"');
}

/* One in-process queue cancel. True when the leaf passes; state holds the
 * reply state and ecode the refusal code (empty on success). */
static bool gw_qcancel(const char *name, char *state, size_t cap,
                       long long *cancelled, char *ecode, size_t ecap)
{
    struct gw_qcall c;
    const struct json_value *v;
    const char *s;
    bool ok;
    gw_qbegin(&c, "cancel");
    (void)json_push_kv_str(&c.input, "name", name);
    zcl_native_handle_dev_agent_queue(&c.req, &c.rep);
    ok = c.rep.status == ZCL_COMMAND_STATUS_PASSED;
    state[0] = '\0';
    ecode[0] = '\0';
    *cancelled = 0;
    v = json_get(&c.rep.data, "state");
    s = (v && v->type == JSON_STR) ? json_get_str(v) : NULL;
    if (s)
        (void)snprintf(state, cap, "%s", s);
    v = json_get(&c.rep.data, "cancelled");
    if (v && v->type == JSON_INT)
        *cancelled = (long long)json_get_int(v);
    if (!ok && c.rep.error.code[0])
        (void)snprintf(ecode, ecap, "%s", c.rep.error.code);
    gw_qend(&c);
    return ok;
}

