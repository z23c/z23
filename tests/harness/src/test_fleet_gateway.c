static pid_t g_gw_pid = -1;
static int g_gw_port = -1;

/* Read one line (no newline) from fd. False on EOF/error/overflow. */
static bool gw_read_line(int fd, char *out, size_t cap)
{
    size_t n = 0;
    while (n + 1 < cap) {
        char c;
        ssize_t r = read(fd, &c, 1);
        if (r <= 0)
            return false;
        if (c == '\n')
            break;
        if (c != '\r')
            out[n++] = c;
    }
    out[n] = '\0';
    return true;
}

/* Spawn the gateway; parse its `ready port=N` line. True when serving.
 * as_kb > 0 caps the child's address space (RLIMIT_AS, the limit ulimit -v
 * sets) so a case can run the same request under exact memory pressure. */
static bool gw_spawn_as(const char *bin, const char *node, const char *state,
                        unsigned long as_kb)
{
    int fds[2];
    char line[256];
    if (pipe(fds) != 0)
        return false;
    g_gw_pid = fork();
    if (g_gw_pid < 0) {
        close(fds[0]);
        close(fds[1]);
        return false;
    }
    if (g_gw_pid == 0) {
        char *const argv[] = {(char *)bin, NULL};
        if (as_kb > 0) {
            struct rlimit rl;
            rl.rlim_cur = (rlim_t)as_kb * 1024u;
            rl.rlim_max = (rlim_t)as_kb * 1024u;
            if (setrlimit(RLIMIT_AS, &rl) != 0)
                _exit(126);
        }
        dup2(fds[1], STDOUT_FILENO);
        close(fds[0]);
        close(fds[1]);
        setenv("FLEET_GW_PORT", "0", 1);
        setenv("FLEET_GW_NODE", node, 1);
        setenv("FLEET_GW_OWNER_KEY", "gw-test-owner-key", 1);
        /* Registration is allowlisted now: without an operator entry only
         * loopback callbacks can register at all. This rig's clients live
         * on client.test, so that is what the operator admits. */
        setenv("FLEET_GW_REDIRECT_ALLOW", "https://client.test", 1);
        /* Short socket deadline and a small child cap so the half-open
         * connection case proves itself in a second rather than ten. */
        setenv("FLEET_GW_IO_TIMEOUT_MS", "1000", 1);
        setenv("FLEET_GW_MAX_CHILDREN", "8", 1);
        setenv("XDG_STATE_HOME", state, 1);
        execv(bin, argv);
        _exit(127);
    }
    close(fds[1]);
    if (!gw_read_line(fds[0], line, sizeof(line))) {
        close(fds[0]);
        return false;
    }
    close(fds[0]);
    if (sscanf(line, "ready port=%d", &g_gw_port) != 1 || g_gw_port <= 0)
        return false;
    return true;
}

static bool gw_spawn(const char *bin, const char *node, const char *state)
{
    return gw_spawn_as(bin, node, state, 0);
}

static void gw_stop(void)
{
    int st = 0;
    if (g_gw_pid < 0)
        return;
    kill(g_gw_pid, SIGTERM);
    waitpid(g_gw_pid, &st, 0);
    g_gw_pid = -1;
    g_gw_port = -1;
}

/* Head (status line + headers) of the most recent exchange, for header
 * assertions such as the OAuth challenge. */
static char g_gw_last_head[2048];

/* One HTTP exchange over loopback. Returns the body (after the blank
 * line) malloc'd, with the status code out. NULL on transport failure. */
static char *gw_exchange(const char *request, int *status)
{
    int fd;
    struct sockaddr_in v4;
    char *buf, *body;
    size_t cap = GW_TEST_CAP, n = 0;
    ssize_t r;
    *status = 0;
    g_gw_last_head[0] = '\0';
    fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0)
        return NULL;
    memset(&v4, 0, sizeof(v4));
    v4.sin_family = AF_INET;
    v4.sin_port = htons((uint16_t)g_gw_port);
    v4.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    if (connect(fd, (struct sockaddr *)&v4, sizeof(v4)) != 0) {
        close(fd);
        return NULL;
    }
    {
        size_t left = strlen(request), off = 0;
        while (left > 0) {
            r = write(fd, request + off, left);
            if (r <= 0) {
                close(fd);
                return NULL;
            }
            off += (size_t)r;
            left -= (size_t)r;
        }
    }
    buf = malloc(cap);
    if (!buf) {
        close(fd);
        return NULL;
    }
    for (;;) {
        if (n + 4096 >= cap) {
            close(fd);
            free(buf);
            return NULL;
        }
        r = read(fd, buf + n, cap - n - 1);
        if (r == 0)
            break;
        if (r < 0) {
            close(fd);
            free(buf);
            return NULL;
        }
        n += (size_t)r;
    }
    close(fd);
    buf[n] = '\0';
    if (sscanf(buf, "HTTP/1.1 %d", status) != 1) {
        free(buf);
        return NULL;
    }
    body = strstr(buf, "\r\n\r\n");
    if (!body) {
        free(buf);
        return NULL;
    }
    snprintf(g_gw_last_head, sizeof(g_gw_last_head), "%.*s",
             (int)(body - buf), buf);
    body += 4;
    {
        size_t blen = n - (size_t)(body - buf);
        char *out = malloc(blen + 1);
        if (!out) {
            free(buf);
            return NULL;
        }
        memcpy(out, body, blen);
        out[blen] = '\0';
        free(buf);
        return out;
    }
}

static char *gw_post(const char *path, const char *json, int *status)
{
    char req[GW_TEST_CAP];
    int n = snprintf(req, sizeof(req),
                     "POST %s HTTP/1.1\r\nHost: x\r\nContent-Type: "
                     "application/json\r\nContent-Length: %zu\r\n"
                     "Connection: close\r\n\r\n%s",
                     path, strlen(json), json);
    if (n <= 0 || (size_t)n >= sizeof(req))
        return NULL;
    return gw_exchange(req, status);
}

static char *gw_post_auth(const char *path, const char *json,
                         const char *bearer, int *status)
{
    char req[GW_TEST_CAP];
    int n;
    if (bearer)
        n = snprintf(req, sizeof(req),
                     "POST %s HTTP/1.1\r\nHost: x\r\nContent-Type: "
                     "application/json\r\nAuthorization: Bearer %s\r\n"
                     "Content-Length: %zu\r\n"
                     "Connection: close\r\n\r\n%s",
                     path, bearer, strlen(json), json);
    else
        n = snprintf(req, sizeof(req),
                     "POST %s HTTP/1.1\r\nHost: x\r\nContent-Type: "
                     "application/json\r\n"
                     "Content-Length: %zu\r\n"
                     "Connection: close\r\n\r\n%s",
                     path, strlen(json), json);
    if (n <= 0 || (size_t)n >= sizeof(req))
        return NULL;
    return gw_exchange(req, status);
}

static char *gw_get(const char *path, int *status)
{
    char req[4096];
    int n = snprintf(req, sizeof(req),
                     "GET %s HTTP/1.1\r\nHost: x\r\nConnection: close\r\n\r\n",
                     path);
    if (n <= 0 || (size_t)n >= sizeof(req))
        return NULL;
    return gw_exchange(req, status);
}

static bool gw_body_has(const char *body, const char *needle)
{
    return body && needle && strstr(body, needle) != NULL;
}

/* Assert on a reply body and SAY WHAT THE BODY WAS when it is wrong.
 *
 * A bare ASSERT(gw_body_has(b, "-32602")) reaches the transcript as one
 * line naming the needle and nothing else, so an intermittent here is
 * indistinguishable from any other -32602 miss: -32603 "arguments too
 * large", -32000 "node did not answer" and a plain success all print the
 * same. That muteness is why the bound-test intermittent survived a
 * qualification run with no diagnosis attached. These print a bounded
 * excerpt of the actual body and its length, which is the whole difference
 * between a rerun and a root cause. */
#define GW_ASSERT_BODY(b, needle) do {                                        \
    const char *gw_b_ = (b);                                                  \
    if (!gw_body_has(gw_b_, (needle))) {                                      \
        printf("FAIL at %s:%d (body missing \"%s\"): len=%zu body=[%.400s]\n",\
               __FILE__, __LINE__, (needle),                                  \
               gw_b_ ? strlen(gw_b_) : (size_t)0,                             \
               gw_b_ ? gw_b_ : "(null)");                                     \
        failures++; goto _test_next;                                          \
    }                                                                         \
} while (0)

#define GW_ASSERT_BODY_NOT(b, needle) do {                                    \
    const char *gw_b_ = (b);                                                  \
    if (gw_body_has(gw_b_, (needle))) {                                       \
        printf("FAIL at %s:%d (body has \"%s\"): len=%zu body=[%.400s]\n",    \
               __FILE__, __LINE__, (needle),                                  \
               gw_b_ ? strlen(gw_b_) : (size_t)0,                             \
               gw_b_ ? gw_b_ : "(null)");                                     \
        failures++; goto _test_next;                                          \
    }                                                                         \
} while (0)

/* Loopback socket to the test gateway, or -1. */
static int gw_sock_open(void)
{
    int fd;
    struct sockaddr_in v4;
    fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0)
        return -1;
    memset(&v4, 0, sizeof(v4));
    v4.sin_family = AF_INET;
    v4.sin_port = htons((uint16_t)g_gw_port);
    v4.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    if (connect(fd, (struct sockaddr *)&v4, sizeof(v4)) != 0) {
        close(fd);
        return -1;
    }
    return fd;
}

/* Whole request out, whole response back (NUL-terminated), or NULL. */
static char *gw_sock_roundtrip(int fd, const char *req)
{
    char *buf;
    size_t cap = 65536, len = 0;
    ssize_t r;
    size_t left = strlen(req), off = 0;
    while (left > 0) {
        r = write(fd, req + off, left);
        if (r <= 0) {
            close(fd);
            return NULL;
        }
        off += (size_t)r;
        left -= (size_t)r;
    }
    buf = malloc(cap);
    if (!buf) {
        close(fd);
        return NULL;
    }
    for (;;) {
        if (len + 4096 >= cap)
            break;
        r = read(fd, buf + len, cap - len - 1);
        if (r <= 0)
            break;
        len += (size_t)r;
    }
    close(fd);
    if (len == 0) {
        free(buf);
        return NULL;
    }
    buf[len] = '\0';
    return buf;
}

/* Location header out of a 302 response, or NULL. */
static char *gw_location_of(char *resp)
{
    char *p, *eol, *out;
    int st = 0;
    if (sscanf(resp, "HTTP/1.1 %d", &st) != 1 || st != 302)
        return NULL;
    p = strstr(resp, "\r\nLocation:");
    if (!p)
        p = strstr(resp, "\r\nlocation:");
    if (!p)
        return NULL;
    p = strchr(p + 2, ':') + 1;
    while (*p == ' ' || *p == '\t')
        p++;
    eol = strstr(p, "\r\n");
    if (!eol)
        return NULL;
    out = malloc((size_t)(eol - p) + 1);
    if (!out)
        return NULL;
    memcpy(out, p, (size_t)(eol - p));
    out[eol - p] = '\0';
    return out;
}

/* One form-encoded POST, optionally carrying an Origin header. The whole
 * raw response comes back so a case can read either its status or its
 * Location. NULL when the connection carried nothing at all. */
static char *gw_post_form_raw(const char *path, const char *form,
                              const char *origin)
{
    char req[GW_TEST_CAP];
    char oh[400];
    int n, fd;
    oh[0] = '\0';
    if (origin && snprintf(oh, sizeof(oh), "Origin: %s\r\n", origin) < 0)
        return NULL;
    n = snprintf(req, sizeof(req),
                 "POST %s HTTP/1.1\r\nHost: x\r\nContent-Type: "
                 "application/x-www-form-urlencoded\r\n%s"
                 "Content-Length: %zu\r\n"
                 "Connection: close\r\n\r\n%s",
                 path, oh, strlen(form), form);
    if (n <= 0 || (size_t)n >= sizeof(req))
        return NULL;
    fd = gw_sock_open();
    if (fd < 0)
        return NULL;
    return gw_sock_roundtrip(fd, req);
}

/* Status code of a form POST, or 0 when nothing came back. */
static int gw_post_form_status(const char *path, const char *form,
                               const char *origin)
{
    char *resp = gw_post_form_raw(path, form, origin);
    int st = 0;
    if (!resp)
        return 0;
    if (sscanf(resp, "HTTP/1.1 %d", &st) != 1)
        st = 0;
    free(resp);
    return st;
}

/* POST form-encoded from the gateway's own origin; returns the Location
 * header value, or NULL. */
static char *gw_post_location(const char *path, const char *form,
                              const char *origin)
{
    char *resp = gw_post_form_raw(path, form, origin);
    char *loc;
    if (!resp)
        return NULL;
    loc = gw_location_of(resp);
    free(resp);
    return loc;
}

/* The gateway's own issuer, which is what its approval page's Origin must
 * be: with FLEET_GW_ISSUER unset the issuer is loopback plus the bound
 * port, exactly as gw_oauth_issuer renders it. */
static const char *gw_self_origin(void)
{
    static char origin[64];
    if (snprintf(origin, sizeof(origin), "http://127.0.0.1:%d", g_gw_port) < 0)
        origin[0] = '\0';
    return origin;
}

/* The single-use approval nonce out of a rendered sign-in page. */
static bool gw_csrf_of(const char *html, char *out, size_t cap)
{
    static const char pat[] = "name=\"csrf\" value=\"";
    const char *p = html ? strstr(html, pat) : NULL;
    const char *q;
    size_t n;
    if (!p)
        return false;
    p += sizeof(pat) - 1;
    q = strchr(p, '"');
    if (!q)
        return false;
    n = (size_t)(q - p);
    if (n == 0 || n + 1 > cap)
        return false;
    memcpy(out, p, n);
    out[n] = '\0';
    return true;
}

/* Count the rows of one JSONL file under the isolated state root. */
static size_t gw_state_rows(const char *state, const char *name)
{
    char path[1024], line[8192];
    size_t rows = 0;
    FILE *f;
    if (snprintf(path, sizeof(path), "%s/z23/dev/steer/%s", state, name) >=
        (int)sizeof(path))
        return 0;
    f = fopen(path, "rb");
    if (!f)
        return 0;
    while (fgets(line, sizeof(line), f))
        rows++;
    (void)fclose(f);
    return rows;
}

/* True when any row of one JSONL file under the state root holds needle. */
static bool gw_state_has(const char *state, const char *name,
                         const char *needle)
{
    char path[1024], line[8192];
    bool hit = false;
    FILE *f;
    if (snprintf(path, sizeof(path), "%s/z23/dev/steer/%s", state, name) >=
        (int)sizeof(path))
        return false;
    f = fopen(path, "rb");
    if (!f)
        return false;
    while (!hit && fgets(line, sizeof(line), f))
        hit = strstr(line, needle) != NULL;
    (void)fclose(f);
    return hit;
}

/* 32-hex value by JSON key out of a body. False when absent/misshapen. */
static bool gw_body_hex(const char *body, const char *key, char *out)
{
    char pat[80];
    const char *p;
    size_t i;
    if (snprintf(pat, sizeof(pat), "\"%s\":\"", key) < 0)
        return false;
    p = body ? strstr(body, pat) : NULL;
    if (!p)
        return false;
    p += strlen(pat);
    for (i = 0; i < 32; i++) {
        char c = p[i];
        bool hex = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f');
        if (!hex)
            return false;
        out[i] = c;
    }
    out[32] = '\0';
    return true;
}

/* Run the node CLI: <node> fleet steer <verb> --input=<json>. Captured
 * stdout malloc'd; NULL on any failure. No shell. */
static char *gw_node_run(const char *node, const char *verb, const char *in)
{
    int fds[2];
    pid_t pid;
    char arg[8192];
    char *out = NULL;
    size_t cap = 65536, n = 0;
    int sn = snprintf(arg, sizeof(arg), "--input=%s", in);
    if (sn <= 0 || (size_t)sn >= sizeof(arg))
        return NULL;
    if (pipe(fds) != 0)
        return NULL;
    pid = fork();
    if (pid < 0) {
        close(fds[0]);
        close(fds[1]);
        return NULL;
    }
    if (pid == 0) {
        char *const argv[] = {(char *)node, (char *)"fleet",
                              (char *)"steer", (char *)verb, arg, NULL};
        dup2(fds[1], STDOUT_FILENO);
        close(fds[0]);
        close(fds[1]);
        execv(node, argv);
        _exit(127);
    }
    close(fds[1]);
    out = malloc(cap);
    if (!out) {
        close(fds[0]);
        waitpid(pid, NULL, 0);
        return NULL;
    }
    for (;;) {
        ssize_t r;
        if (n + 4096 >= cap)
            break;
        r = read(fds[0], out + n, cap - n - 1);
        if (r <= 0)
            break;
        n += (size_t)r;
    }
    close(fds[0]);
    waitpid(pid, NULL, 0);
    if (n == 0) {
        free(out);
        return NULL;
    }
    out[n] = '\0';
    return out;
}

/* Mint a steering grant through the node CLI; copies the 32-hex id out.
 * Every grant here is minted under GW_SENDER, because a grant's label is
 * the sender it may speak as and a send that claims any other name is
 * refused. A rig grant with no label could send as nobody. */
static bool gw_mint(const char *node, const char *scopes, char *id_out)
{
    char in[256];
    char *reply;
    const char *p;
    int sn = snprintf(in, sizeof(in),
                      "{\"action\":\"mint\",\"scopes\":\"%s\","
                      "\"label\":\"" GW_SENDER "\"}", scopes);
    if (sn <= 0 || (size_t)sn >= sizeof(in))
        return false;
    reply = gw_node_run(node, "grant", in);
    if (!reply)
        return false;
    p = strstr(reply, "\"id\":\"");
    if (!p || strlen(p + 6) < 32) {
        free(reply);
        return false;
    }
    memcpy(id_out, p + 6, 32);
    id_out[32] = '\0';
    free(reply);
    return true;
}

static const char *gw_bin(const char *env, const char *dflt)
{
    const char *v = getenv(env);
    return v && v[0] ? v : dflt;
}

/* First mail seq out of an escaped send body (\"seq\":N). -1 when absent. */
static long long gw_body_seq(const char *body)
{
    const char *p = body ? strstr(body, "\\\"seq\\\":") : NULL;
    char *end = NULL;
    long long s;
    if (!p)
        return -1;
    s = strtoll(p + 8, &end, 10);
    if (end == p + 8 || s < 0)
        return -1;
    return s;
}

/* Receiver-side ack through the real mail leaf, in-process (receivers act
 * locally; the gateway only ever reads). The mail CLI leaf is compat-only,
 * so fork/exec cannot ack: same pattern as the steer group's fmx_ack. */
static bool gw_mail_ack(const char *agent, long long cursor)
{
    struct json_value input;
    struct zcl_command_request request;
    struct zcl_command_reply reply;
    bool ok;
    json_init(&input);
    json_set_object(&input);
    memset(&request, 0, sizeof(request));
    request.input = &input;
    request.spec =
        zcl_command_registry_find(zcl_command_catalog(), "dev.agent.mail",
                                  NULL);
    zcl_command_reply_init(&reply, "zcl.agent_mail.v1");
    (void)json_push_kv_str(&input, "action", "ack");
    (void)json_push_kv_str(&input, "agent", agent);
    (void)json_push_kv_int(&input, "cursor", cursor);
    zcl_native_handle_dev_agent_mail(&request, &reply);
    ok = reply.status == ZCL_COMMAND_STATUS_PASSED;
    zcl_command_reply_free(&reply);
    json_free(&input);
    return ok;
}

