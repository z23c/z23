        sn = snprintf(args, sizeof(args),
                      "{\"jsonrpc\":\"2.0\",\"id\":23,\"method\":\"tools/"
                      "call\",\"params\":{\"name\":\"steer_brief\","
                      "\"arguments\":{\"grant\":\"00000000000000000000000000"
                      "00000000\"}}}");
        ASSERT(sn > 0 && (size_t)sn < sizeof(args));
        b = gw_post_auth("/steer", args, gid, &st);
