/* Verdict+rc out of one outcome row naming name. False when the row is
 * absent or malformed. */
static bool gw_qrow_match(const struct json_value *r, const char *name,
                          char *verdict, size_t vcap, long long *rc)
{
    const struct json_value *v, *rv;
    const char *n, *vd, *sv;
    long long rrc;
    if (!r || r->type != JSON_OBJ)
        return false;
    v = json_get(r, "name");
    n = (v && v->type == JSON_STR) ? json_get_str(v) : NULL;
    if (!n || strcmp(n, name) != 0)
        return false;
    v = json_get(r, "verdict");
    vd = (v && v->type == JSON_STR) ? json_get_str(v) : NULL;
    rv = json_get(r, "rc");
    rrc = (rv && rv->type == JSON_INT) ? (long long)json_get_int(rv) : -1;
    sv = vd ? vd : "";
    if (snprintf(verdict, vcap, "%s", sv) <= 0)
        return false;
    *rc = rrc;
    return true;
}

/* Reap and report the outcome row for one name. True when reap passes;
 * found tells whether a row named name was recorded. */
static bool gw_qreap_scan(const char *name, char *verdict, size_t vcap,
                          long long *rc, bool *found)
{
    struct gw_qcall c;
    const struct json_value *rows;
    size_t i, nrows;
    bool ok = false;
    *found = false;
    gw_qbegin(&c, "reap");
    if (!gw_qrun(&c)) {
        gw_qend(&c);
        return false;
    }
    ok = true;
    rows = json_get(&c.rep.data, "outcomes");
    if (rows && rows->type == JSON_ARR) {
        nrows = json_size(rows);
        for (i = 0; i < nrows; i++) {
            if (gw_qrow_match(json_at(rows, i), name, verdict, vcap, rc))
                *found = true;
        }
    }
    gw_qend(&c);
    return ok;
}

/* Decode the gateway's text content without losing cursor or truncation fields. */
static bool gw_mailbox_reply(const char *body, struct json_value *data)
{
    struct json_value envelope = {0};
    bool ok = false;
    if (json_read(&envelope, body, strlen(body))) {
        const struct json_value *result = json_get(&envelope, "result");
        const struct json_value *item = json_at(json_get(result, "content"), 0);
        const char *text = json_get_str(json_get(item, "text"));
        ok = text && json_read(data, text, strlen(text));
    }
    json_free(&envelope);
    return ok;
}

/* Use the sent row's own timestamp, not the host's current calendar year. */
static bool gw_reply_after_sent(const char *body, const char *ref, char out[32])
{
    struct json_value parsed = {0};
    bool ok = gw_mailbox_reply(body, &parsed);
    const struct json_value *rows = json_get(&parsed, "changes");
    const char *stamp = NULL;
    for (size_t i = 0; ok && i < json_size(rows); i++) {
        const struct json_value *row = json_at(rows, i);
        const char *r = json_get_str(json_get(row, "ref"));
        const char *from = json_get_str(json_get(row, "from"));
        if (r && from && !strcmp(r, ref) && !strcmp(from, GW_SENDER)) {
            stamp = json_get_str(json_get(json_get(row, "reply"), "sent_ts"));
            break;
        }
    }
    int64_t seconds;
    ok = stamp && fo_parse_iso8601(stamp, &seconds) && seconds < INT64_MAX;
    time_t next = ok ? (time_t)(seconds + 1) : 0;
    struct tm utc;
    ok = ok && (int64_t)next == seconds + 1 && zcl_utc_tm(next, &utc) &&
         strftime(out, 32, "%Y-%m-%dT%H:%M:%SZ", &utc) == 20;
    json_free(&parsed);
    return ok;
}

static char *gw_mailbox_http(const char *grant, const char *to,
                             const char *cursor, int *status)
{
    struct json_value args = {0};
    char encoded[12000], request[12500];
    json_set_object(&args);
    bool ok = json_push_kv_str(&args, "to", to) &&
              json_push_kv_str(&args, "ref", "gw-mailbox-") &&
              (!cursor[0] || json_push_kv_str(&args, "since", cursor)) &&
              json_push_kv_int(&args, "limit", 1);
    size_t n = ok ? json_write(&args, encoded, sizeof(encoded)) : 0;
    json_free(&args);
    if (!n || n >= sizeof(encoded))
        return NULL;
    int count = snprintf(request, sizeof(request),
        "{\"jsonrpc\":\"2.0\",\"id\":81,\"method\":\"tools/call\","
        "\"params\":{\"name\":\"steer_mailbox\",\"arguments\":%s}}", encoded);
    if (count <= 0 || (size_t)count >= sizeof(request))
        return NULL;
    return gw_post_auth("/steer", request, grant, status);
}

