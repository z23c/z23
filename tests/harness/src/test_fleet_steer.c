/* ── isolated state root (this group owns its own rig) ─────────────────── */

static char g_fmx_state[1024];
static bool g_fmx_had_root;
static bool g_fmx_isolated;
#if defined(_WIN32)
static wchar_t g_fmx_saved_root[32768];
#else
static char g_fmx_saved_root[4096];
#endif

static void fmx_fixture_fail(const char *context)
{
    fprintf(stderr, "fleet_steer fixture: %s\n", context);
    abort();
}

#if defined(_WIN32)
static void fmx_isolate_env(const char *state)
{
    wchar_t root[1024];
    g_fmx_saved_root[0] = L'\0';
    SetLastError(ERROR_SUCCESS);
    DWORD length = GetEnvironmentVariableW(L"ZCL_STATE_ROOT", g_fmx_saved_root,
                                           32768);
    DWORD error = GetLastError();
    if (length >= 32768 || (length == 0 && error != ERROR_SUCCESS &&
                            error != ERROR_ENVVAR_NOT_FOUND))
        fmx_fixture_fail("could not preserve ZCL_STATE_ROOT");
    g_fmx_had_root = length > 0 || error == ERROR_SUCCESS;
    if (MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS, state, -1,
                            root, 1024) <= 0 ||
        !SetEnvironmentVariableW(L"ZCL_STATE_ROOT", root))
        fmx_fixture_fail("could not isolate ZCL_STATE_ROOT");
}
#else
static void fmx_isolate_env(const char *state)
{
    const char *original = getenv("XDG_STATE_HOME");
    g_fmx_had_root = original != NULL;
    if (original) {
        int n = snprintf(g_fmx_saved_root, sizeof(g_fmx_saved_root), "%s",
                         original);
        if (n < 0 || (size_t)n >= sizeof(g_fmx_saved_root))
            fmx_fixture_fail("could not preserve XDG_STATE_HOME");
    }
    if (setenv("XDG_STATE_HOME", state, 1) != 0)
        fmx_fixture_fail("could not isolate XDG_STATE_HOME");
}
#endif

static void fmx_isolate(const char *tag)
{
    char base[512];
    if (g_fmx_isolated)
        fmx_fixture_fail("previous state root has not been restored");
    test_make_tmpdir(base, sizeof(base), "fleet_steer", tag);
    int n = snprintf(g_fmx_state, sizeof(g_fmx_state), "%s/state", base);
    if (n <= 0 || (size_t)n >= sizeof(g_fmx_state) ||
        !platform_private_directory_ensure(g_fmx_state))
        fmx_fixture_fail("could not create isolated state parent");
    fmx_isolate_env(g_fmx_state);
    g_fmx_isolated = true;
}

static void fmx_restore(void)
{
    if (!g_fmx_isolated) return;
#if defined(_WIN32)
    if (!SetEnvironmentVariableW(L"ZCL_STATE_ROOT",
                                 g_fmx_had_root ? g_fmx_saved_root : NULL))
        fmx_fixture_fail("could not restore ZCL_STATE_ROOT");
#else
    int rc = g_fmx_had_root ? setenv("XDG_STATE_HOME", g_fmx_saved_root, 1)
                            : unsetenv("XDG_STATE_HOME");
    if (rc != 0)
        fmx_fixture_fail("could not restore XDG_STATE_HOME");
#endif
    g_fmx_isolated = false;
}

/* ── one in-process invocation ─────────────────────────────────────────── */

struct fmx_call {
    struct json_value input;
    struct zcl_command_request request;
    struct zcl_command_reply reply;
};

static void fmx_begin(struct fmx_call *c, const char *path,
                      const char *schema)
{
    json_init(&c->input);
    json_set_object(&c->input);
    memset(&c->request, 0, sizeof(c->request));
    c->request.input = &c->input;
    c->request.spec =
        zcl_command_registry_find(zcl_command_catalog(), path, NULL);
    zcl_command_reply_init(&c->reply, schema);
}

static bool fmx_run(struct fmx_call *c,
                    void (*handler)(const struct zcl_command_request *,
                                    struct zcl_command_reply *))
{
    char why[256];
    if (c->request.spec &&
        !zcl_command_registry_input_validate(c->request.spec, &c->input, why,
                                             sizeof(why))) {
        printf("[input rejected: %s] ", why);
        return false;
    }
    handler(&c->request, &c->reply);
    return true;
}

static void fmx_end(struct fmx_call *c)
{
    zcl_command_reply_free(&c->reply);
    json_free(&c->input);
}

static bool fmx_ok(const struct fmx_call *c)
{
    return c->reply.status == ZCL_COMMAND_STATUS_PASSED;
}

static const struct json_value *fmx_get(const struct fmx_call *c,
                                        const char *key)
{
    return json_get(&c->reply.data, key);
}

static const char *fmx_str(const struct fmx_call *c, const char *key)
{
    const struct json_value *v = fmx_get(c, key);
    return v && v->type == JSON_STR && json_get_str(v) ? json_get_str(v) : "";
}

static const struct json_value *fmx_arr(const struct fmx_call *c,
                                        const char *key)
{
    const struct json_value *v = fmx_get(c, key);
    return v && v->type == JSON_ARR ? v : NULL;
}

/* Integer reply field, or -1 when absent/wrong-typed. */
static long long fmx_int(const struct fmx_call *c, const char *key)
{
    const struct json_value *v = fmx_get(c, key);
    return v && v->type == JSON_INT ? json_get_int(v) : -1;
}

/* True when missing[] names the given source. */
static bool fmx_missing_has(const struct fmx_call *c, const char *source)
{
    const struct json_value *missing = fmx_arr(c, "missing");
    size_t n, i;
    if (!missing)
        return false;
    n = json_size(missing);
    for (i = 0; i < n; i++) {
        const struct json_value *e = json_at(missing, i);
        const struct json_value *v;
        const char *s;
        if (!e || e->type != JSON_OBJ)
            continue;
        v = json_get(e, "source");
        s = (v && v->type == JSON_STR) ? json_get_str(v) : NULL;
        if (s && strcmp(s, source) == 0)
            return true;
    }
    return false;
}

/* Mint a grant through the real leaf under an explicit sender label;
 * copies the id out before freeing. */
static bool fmx_mint_as(const char *scopes, const char *label, char *id_out,
                        size_t id_cap)
{
    struct fmx_call g;
    const char *id;
    bool ok = false;
    fmx_begin(&g, FMX_GRANT_PATH, "zcl.fleet_steer_grant.v1");
    (void)json_push_kv_str(&g.input, "action", "mint");
    (void)json_push_kv_str(&g.input, "scopes", scopes);
    if (label)
        (void)json_push_kv_str(&g.input, "label", label);
    if (!fmx_run(&g, zcl_native_handle_fleet_steer_grant) || !fmx_ok(&g)) {
        fmx_end(&g);
        return false;
    }
    id = fmx_str(&g, "id");
    if (id[0] && strlen(id) == 32 && strlen(id) < id_cap) {
        snprintf(id_out, id_cap, "%s", id);
        ok = true;
    }
    fmx_end(&g);
    return ok;
}

/* The ordinary fixture grant: one live credential speaking as FMX_SENDER. */
static bool fmx_mint(const char *scopes, char *id_out, size_t id_cap)
{
    return fmx_mint_as(scopes, FMX_SENDER, id_out, id_cap);
}

