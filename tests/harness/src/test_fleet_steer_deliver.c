/* ── abuse bounds, faults and races ─────────────────────────────────────── */

static int64_t g_fsd_ms;
static int64_t fsd_clock_wall(void *self)
{
    (void)self;
    return g_fsd_ms;
}
static int64_t fsd_clock_mono(void *self)
{
    (void)self;
    return g_fsd_ms * 1000000;
}
static const clock_iface_t g_fsd_clock = {fsd_clock_mono, fsd_clock_wall, NULL};

/* An hour-aligned instant: every window starts empty. */
#define FSD_T0 1800000000LL

static void fsd_clock_at(long long sec)
{
    g_fsd_ms = sec * 1000;
    clock_set_default(&g_fsd_clock);
}

/* Run one chunk call in a fresh process (all accounting is read from disk)
 * and return a small code for its outcome. */
static int fsd_child(const char *grant, const char *from, const char *uid,
                     size_t size, const char *sha, long long off, int flip)
{
    int status = 0;
    pid_t pid = fork();
    if (pid == 0) {
        char buf[64];
        static const char *const names[] = {
            "", "STEER_DELIVER_RATE", "STEER_DELIVER_OUTSTANDING",
            "STEER_DELIVER_BUSY", "STEER_DELIVER_CONFLICT",
            "STEER_DELIVER_HASH_MISMATCH", "STEER_DELIVER_BYTE_RATE"};
        size_t i;
        int code = 99;
        if (flip >= 0)
            g_fsd_file[flip] ^= 1;
        (void)fsd_chunk(grant, from, uid, size, sha, off, buf, sizeof(buf));
        for (i = 0; i < sizeof(names) / sizeof(names[0]); i++)
            if (strcmp(buf, names[i]) == 0)
                code = (int)i;
        _exit(code);
    }
    if (pid < 0 || waitpid(pid, &status, 0) != pid || !WIFEXITED(status))
        return -1;
    return WEXITSTATUS(status);
}

static bool fsd_bind_dir(const char *uid, char *out, size_t cap)
{
    char *slash;
    if (!fsd_updir(uid, out, cap))
        return false;
    slash = strrchr(out, '/');
    if (!slash)
        return false;
    *slash = '\0';
    return true;
}

