/* Two processes send the same chunk: each is accepted (or duplicate) or told
 * BUSY, and the object ends quarantined with the verified digest. */
static bool fsd_race_identical(const char *g, const char *label,
                               const char *uid, const char *sha)
{
    char buf[64];
    int a, b = 0;
    pid_t p = fork();
    if (p == 0)
        _exit(fsd_child(g, label, uid, 100, sha, 0, -1));
    a = fsd_child(g, label, uid, 100, sha, 0, -1);
    if (p < 0 || waitpid(p, &b, 0) != p)
        return false;
    b = WEXITSTATUS(b);
    if (!((a == 0 || a == 3) && (b == 0 || b == 3) && (a == 0 || b == 0)))
        return false;
    return fsd_chunk(g, label, uid, 100, sha, 0, buf, sizeof(buf))[0] == '\0' &&
           fsd_state_is(uid, "quarantined");
}

/* One process sends the right bytes, the other a changed byte: the changed
 * one never succeeds, and quarantined appears only for the declared bytes. */
static bool fsd_race_conflict(const char *g, const char *label,
                              const char *uid, const char *sha)
{
    int a, b = 0;
    pid_t p = fork();
    if (p == 0)
        _exit(fsd_child(g, label, uid, 100, sha, 0, 3));
    a = fsd_child(g, label, uid, 100, sha, 0, -1);
    if (p < 0 || waitpid(p, &b, 0) != p)
        return false;
    b = WEXITSTATUS(b);
    if (b == 0 || b == 99 || !(a == 0 || a == 3 || a == 4 || a == 5))
        return false;
    return fsd_state_is(uid, a == 0 ? "quarantined" : "failed") ||
           fsd_state_is(uid, "failed");
}

