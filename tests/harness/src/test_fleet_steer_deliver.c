static char g_fsd_state[1024];
static char g_fsd_saved[1024];
static bool g_fsd_had;
static bool g_fsd_active;
static char g_fsd_base[512];
static unsigned char g_fsd_file[FSD_MAX + 1];
static const char *g_fsd_name = "main.c";

struct fsd_call {
    struct json_value in;
    struct zcl_command_request rq;
    struct zcl_command_reply rp;
};

static void fsd_restore(void);

static void fsd_isolate(const char *tag)
{
    char base[512];
    const char *old;
    fsd_restore();
    old = getenv("XDG_STATE_HOME");
    g_fsd_had = old != NULL;
    snprintf(g_fsd_saved, sizeof(g_fsd_saved), "%s", old ? old : "");
    test_make_tmpdir(base, sizeof(base), "fleet_steer_deliver", tag);
    snprintf(g_fsd_base, sizeof(g_fsd_base), "%s", base);
    g_fsd_active = true;
    snprintf(g_fsd_state, sizeof(g_fsd_state), "%s/state", base);
    if (!platform_private_directory_ensure(g_fsd_state) ||
        setenv("XDG_STATE_HOME", g_fsd_state, 1) != 0)
        abort();
}

/* Idempotent: removes the isolated base even when a failing ASSERT skipped
 * the explicit restore at the end of a case. */
static void fsd_restore(void)
{
    if (!g_fsd_active) return;
    g_fsd_active = false;
    if (g_fsd_had)
        setenv("XDG_STATE_HOME", g_fsd_saved, 1);
    else
        unsetenv("XDG_STATE_HOME");
    (void)test_rm_rf_recursive(g_fsd_base);
}

static void fsd_fill(size_t size, unsigned seed)
{
    size_t i;
    for (i = 0; i < size; i++)
        g_fsd_file[i] = (unsigned char)((i * 131u + seed * 17u + 7u) & 0xffu);
}

static void fsd_sha(size_t size, char *out)
{
    unsigned char sum[SHA3_512_OUTPUT_SIZE];
    zcl_sha3_512(g_fsd_file, size, sum);
    zcl_hex_encode(sum, sizeof(sum), out);
}

static bool fsd_mint(const char *scopes, const char *label, char *id)
{
    struct fsd_call c;
    bool ok;
    json_init(&c.in);
    json_set_object(&c.in);
    memset(&c.rq, 0, sizeof(c.rq));
    c.rq.input = &c.in;
    zcl_command_reply_init(&c.rp, "zcl.fleet_steer_grant.v1");
    (void)json_push_kv_str(&c.in, "action", "mint");
    (void)json_push_kv_str(&c.in, "scopes", scopes);
    if (label)
        (void)json_push_kv_str(&c.in, "label", label);
    zcl_native_handle_fleet_steer_grant(&c.rq, &c.rp);
    ok = c.rp.status == ZCL_COMMAND_STATUS_PASSED;
    if (ok)
        snprintf(id, 40, "%s", json_get_str(json_get(&c.rp.data, "id")));
    zcl_command_reply_free(&c.rp);
    json_free(&c.in);
    return ok;
}

static void fsd_revoke(const char *id)
{
    struct fsd_call c;
    json_init(&c.in);
    json_set_object(&c.in);
    memset(&c.rq, 0, sizeof(c.rq));
    c.rq.input = &c.in;
    zcl_command_reply_init(&c.rp, "zcl.fleet_steer_grant.v1");
    (void)json_push_kv_str(&c.in, "action", "revoke");
    (void)json_push_kv_str(&c.in, "id", id);
    zcl_native_handle_fleet_steer_grant(&c.rq, &c.rp);
    zcl_command_reply_free(&c.rp);
    json_free(&c.in);
}

/* One deliver call for the chunk at `offset` of g_fsd_file[0..size). */
static void fsd_call(struct fsd_call *c, const char *grant, const char *from,
                     const char *uid, size_t size, const char *sha,
                     long long offset)
{
    size_t left = (long long)size > offset ? size - (size_t)offset : 0;
    size_t n = left > FSI_CHUNK ? FSI_CHUNK : left;
    char *hex = calloc(1, 2 * FSI_CHUNK + 2);
    if (!hex)
        abort();
    zcl_hex_encode(g_fsd_file + offset, n, hex);
    json_init(&c->in);
    json_set_object(&c->in);
    memset(&c->rq, 0, sizeof(c->rq));
    c->rq.input = &c->in;
    zcl_command_reply_init(&c->rp, "zcl.fleet_steer_deliver.v1");
    if (grant)
        (void)json_push_kv_str(&c->in, "grant", grant);
    if (from)
        (void)json_push_kv_str(&c->in, "from", from);
    (void)json_push_kv_str(&c->in, "ref", "job-1");
    (void)json_push_kv_str(&c->in, "upload_id", uid);
    (void)json_push_kv_str(&c->in, "name", g_fsd_name);
    (void)json_push_kv_int(&c->in, "size", (long long)size);
    (void)json_push_kv_str(&c->in, "sha3_512", sha);
    (void)json_push_kv_int(&c->in, "offset", offset);
    (void)json_push_kv_str(&c->in, "data_hex", hex);
    free(hex);
    zcl_native_handle_fleet_steer_deliver(&c->rq, &c->rp);
}

static void fsd_end(struct fsd_call *c)
{
    zcl_command_reply_free(&c->rp);
    json_free(&c->in);
}

/* Refusal code of a call, "" when it passed. Frees the call. */
static const char *fsd_code(struct fsd_call *c, char *buf, size_t cap)
{
    buf[0] = '\0';
    if (c->rp.status != ZCL_COMMAND_STATUS_PASSED)
        snprintf(buf, cap, "%s", c->rp.error.code);
    fsd_end(c);
    return buf;
}

static const char *fsd_chunk(const char *grant, const char *from,
                             const char *uid, size_t size, const char *sha,
                             long long off, char *buf, size_t cap)
{
    struct fsd_call c;
    fsd_call(&c, grant, from, uid, size, sha, off);
    return fsd_code(&c, buf, cap);
}

/* Upload every chunk; the last refusal code, "" when all passed. */
static const char *fsd_all(const char *grant, const char *from,
                           const char *uid, size_t size, const char *sha,
                           char *buf, size_t cap)
{
    long long off;
    buf[0] = '\0';
    for (off = 0; off < (long long)size && !buf[0]; off += FSI_CHUNK)
        (void)fsd_chunk(grant, from, uid, size, sha, off, buf, cap);
    return buf;
}

static bool fsd_state_is(const char *uid, const char *want)
{
    struct fsd_call c;
    const struct json_value *rows;
    bool ok = false;
    json_init(&c.in);
    json_set_object(&c.in);
    memset(&c.rq, 0, sizeof(c.rq));
    c.rq.input = &c.in;
    zcl_command_reply_init(&c.rp, "zcl.fleet_steer_inbox.v1");
    zcl_native_handle_fleet_steer_inbox(&c.rq, &c.rp);
    rows = json_get(&c.rp.data, "uploads");
    for (size_t i = 0; rows && i < json_size(rows); i++) {
        const struct json_value *r = json_at(rows, i);
        const char *id = json_get_str(json_get(r, "upload"));
        if (strstr(id, uid) != NULL)
            ok = strcmp(json_get_str(json_get(r, "state")), want) == 0;
    }
    fsd_end(&c);
    return ok;
}

/* Path of the first upload dir below the first binding dir. */
static bool fsd_updir(const char *uid, char *out, size_t cap)
{
    char root[1400];
    DIR *d;
    struct dirent *e;
    bool found = false;
    snprintf(root, sizeof(root), "%s/z23/dev/steer/inbox", g_fsd_state);
    d = opendir(root);
    while (d && !found && (e = readdir(d)) != NULL) {
        if (strlen(e->d_name) == 32) {
            snprintf(out, cap, "%s/%s/%s", root, e->d_name, uid);
            found = access(out, F_OK) == 0;
        }
    }
    if (d)
        (void)closedir(d);
    return found;
}

static bool fsd_inbox_absent(void)
{
    char p[1400];
    snprintf(p, sizeof(p), "%s/z23/dev/steer/inbox", g_fsd_state);
    return access(p, F_OK) != 0;
}

