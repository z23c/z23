static bool sct_is_str(const struct json_value *v, const char *s)
{
    return v != NULL && v->type == JSON_STR && strcmp(json_get_str(v), s) == 0;
}

static bool sct_is_int(const struct json_value *v, int64_t n)
{
    return v != NULL && v->type == JSON_INT && json_get_int(v) == n;
}

static bool sct_facts_ok(const struct json_value *facts,
                         const struct json_value *u, int64_t total,
                         int64_t listed)
{
    const struct json_value *complete = u ? json_get(u, "complete") : NULL;
    return u != NULL &&
           sct_is_str(json_get(facts, "consumer"), "zcl.semantic_consumer.v1") &&
           complete != NULL && complete->type == JSON_BOOL &&
           json_get_bool(complete) && sct_is_int(json_get(u, "total"), total) &&
           sct_is_int(json_get(u, "listed"), listed) &&
           json_get(facts, "obligations") != NULL && json_get(facts, "tus") != NULL;
}

