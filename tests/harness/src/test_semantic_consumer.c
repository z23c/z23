/* dev.change.plan through the real handler in a child that moved to root;
 * 0 when the facts object names the consumer, a complete universe of
 * `total` TUs, and lists `listed` entries from `offset`. */
static int sct_cmd(const char *root, size_t offset, int64_t total,
                   int64_t listed)
{
    int st = 0;
    pid_t pid = fork();
    if (pid == 0) {
        char input[512];
        struct json_value in;
        struct zcl_command_request req;
        struct zcl_command_reply r;
        const struct json_value *facts, *u;
        int rc = 1;
        (void)snprintf(input, sizeof(input),
                       "{\"files\":[\"" SCX_HEADER "\"],\"facts\":\"facts\","
                       "\"facts_offset\":%zu}", offset);
        json_init(&in);
        zcl_command_reply_init(&r, "zcl.dev_plan.v1");
        if (chdir(root) == 0 && json_read(&in, input, strlen(input))) {
            memset(&req, 0, sizeof(req));
            req.input = &in;
            req.spec = zcl_command_registry_find(zcl_command_catalog(),
                                                 "dev.change.plan", NULL);
            zcl_native_handle_dev_change_plan(&req, &r);
            facts = json_get(&r.data, "facts");
            u = facts ? json_get(facts, "universe") : NULL;
            rc = r.status == ZCL_COMMAND_STATUS_PASSED &&
                         sct_facts_ok(facts, u, total, listed)
                     ? 0
                     : 1;
        }
        zcl_command_reply_free(&r);
        json_free(&in);
        _exit(rc);
    }
    if (pid < 0 || waitpid(pid, &st, 0) != pid || !WIFEXITED(st))
        return -1;
    return WEXITSTATUS(st);
}
#endif

